-- أحكام العبادات: فئات وأحكام فقهية موثّقة المصدر (إسلام ويب - مركز الفتوى، وموقع الشيخ ابن باز)
-- كل حكم يحمل رابط المصدر الأصلي للرجوع إليه والتحقق منه.

create table public.ibadah_categories (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  icon text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table public.ibadah_rulings (
  id uuid primary key default gen_random_uuid(),
  category_id uuid not null references public.ibadah_categories(id) on delete cascade,
  title text not null,
  question text,
  answer text not null,
  source_name text not null,
  source_url text not null,
  scholar text,
  madhhab text,
  verified boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.ibadah_categories enable row level security;
alter table public.ibadah_rulings enable row level security;

create policy "Categories are public" on public.ibadah_categories for select using (true);
create policy "Admins manage categories" on public.ibadah_categories for all
  using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');

create policy "Verified rulings are public" on public.ibadah_rulings for select
  using (verified = true or public.current_user_role() = 'admin');
create policy "Admins manage rulings" on public.ibadah_rulings for all
  using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');

create index ibadah_rulings_category_idx on public.ibadah_rulings (category_id, sort_order);

